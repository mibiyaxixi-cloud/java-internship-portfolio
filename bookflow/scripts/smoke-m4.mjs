import assert from 'node:assert/strict'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { client } from './http-client.mjs'
process.loadEnvFile(fileURLToPath(new URL('../.env', import.meta.url)))
const base = process.env.API_BASE || 'http://127.0.0.1:8080'
const a = client(base), b = client(base), admin = client(base)
await a.login('student', process.env.DEMO_USER_PASSWORD)
await b.login('student2', process.env.DEMO_SECOND_USER_PASSWORD)
await admin.login('admin', process.env.DEMO_ADMIN_PASSWORD)
const date = new Intl.DateTimeFormat('sv-SE', { timeZone:'Asia/Shanghai', year:'numeric', month:'2-digit', day:'2-digit' }).format(new Date(Date.now()+2*86400000))
const deviceBody = { code:`M4-${Date.now().toString(36).toUpperCase()}`, name:'【M4 验收】候补演示设备', category:'验收数据', location:'本地演示实验室', description:'自动验收创建，非真实设备；预约和候补历史保留。', status:'ACTIVE' }
const device = await admin.write('/api/admin/devices','POST',deviceBody,201)
const slot = await admin.write(`/api/admin/devices/${device.id}/slots`,'POST',{startAt:`${date}T09:00:00`,endAt:`${date}T10:00:00`,status:'OPEN'},201)
const token = crypto.randomUUID()
const first = await a.write('/api/reservations','POST',{slotId:slot.id},201,token)
const replay = await a.write('/api/reservations','POST',{slotId:slot.id},201,token)
assert.deepEqual(replay,first); assert.equal(a.lastHeaders.get('Idempotency-Replayed'),'true')
await a.write('/api/reservations','POST',{slotId:slot.id+999999},409,token)
console.log('PASS persisted request replay and key/resource binding')
const joinKey = crypto.randomUUID()
const wb = await b.write('/api/waitlist','POST',{slotId:slot.id},201,joinKey)
assert.deepEqual(await b.write('/api/waitlist','POST',{slotId:slot.id},201,joinKey),wb)
const wc = await admin.write('/api/waitlist','POST',{slotId:slot.id},201)
assert.equal(wb.position,1); assert.equal(wc.position,2)
await a.write(`/api/waitlist/${wb.id}/confirm`,'POST',undefined,403)
await a.write(`/api/waitlist/${wb.id}/withdraw`,'POST',undefined,403)
await a.send('/api/admin/waitlist/tasks',{},403)
console.log('PASS FIFO queue, repeated join and backend ownership/role checks')
await a.write(`/api/reservations/${first.reservation.id}/cancel`)
const offered = (await b.send('/api/waitlist/mine')).find(x=>x.id===wb.id)
assert.equal(offered.status,'OFFERED'); assert.ok(offered.expiresAt)
const held = (await b.send('/api/reservations/mine')).find(x=>x.reservation.id===offered.reservationId)
assert.equal(held.reservation.status,'HELD'); assert.equal(held.cancellable,false)
await a.write('/api/reservations','POST',{slotId:slot.id},409)
console.log('PASS cancellation atomically offers the first waiter and blocks direct booking')
if (process.argv.includes('--prepare-ui')) {
  writeFileSync(new URL('../.local/m4-ui-scenario.json',import.meta.url), JSON.stringify({deviceId:device.id,slotId:slot.id,waitlistId:wb.id,expiresAt:offered.expiresAt})+'\n')
  console.log(`UI scenario ready: student2 can confirm waitlist #${wb.id} on device #${device.id}.`)
} else {
  const confirmKey = crypto.randomUUID()
  const confirmed = await b.write(`/api/waitlist/${wb.id}/confirm`,'POST',undefined,200,confirmKey)
  assert.equal(confirmed.reservation.id,offered.reservationId); assert.equal(confirmed.reservation.status,'CONFIRMED')
  assert.deepEqual(await b.write(`/api/waitlist/${wb.id}/confirm`,'POST',undefined,200,confirmKey),confirmed)
  await b.write(`/api/reservations/${confirmed.reservation.id}/cancel`)
  assert.equal((await admin.send('/api/waitlist/mine')).find(x=>x.id===wc.id).status,'OFFERED')
  await admin.write(`/api/waitlist/${wc.id}/withdraw`)
  const newBooking = await a.write('/api/reservations','POST',{slotId:slot.id},201)
  assert.notEqual(newBooking.reservation.id,first.reservation.id)
  assert.deepEqual(await a.write('/api/reservations','POST',{slotId:slot.id},201,token),first)
  await a.write(`/api/reservations/${newBooking.reservation.id}/cancel`)
  console.log('PASS confirmation retry, second handoff, withdrawal, new intent and old-key snapshot replay')
  const task = (await admin.send('/api/admin/waitlist/tasks')).find(x=>x.slotId===slot.id)
  assert.equal(task.status,'DONE'); assert.equal(task.failureCount,0)
  await admin.write(`/api/admin/slots/${slot.id}`,'DELETE',undefined,409)
  await admin.write(`/api/admin/devices/${device.id}`,'PUT',{...deviceBody,status:'INACTIVE'})
  writeFileSync(new URL('../.local/m4-smoke-result.json',import.meta.url),JSON.stringify({checkedAt:new Date().toISOString(),deviceId:device.id,slotId:slot.id,waitlistIds:[wb.id,wc.id],taskStatus:task.status,checks:5},null,2)+'\n')
  console.log('PASS persisted task reaches DONE; historical data remains protected')
}
for(const session of [a,b,admin]) await session.write('/api/auth/logout','POST',undefined,204)
